/**
 * Rebuilds src/lib/glossaryData.ts from docs/glossary/BJJ_glossary_D8_only.csv.
 * Run: node scripts/build-glossary.mjs
 * The CSV is the owner-reviewed D8-only glossary. Every row has one of the eight D8 faces.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const FACE_IDS = {
  'Guard/Control': 'guard-control',
  Passing: 'passing',
  Sweeps: 'sweeps',
  Takedowns: 'takedowns',
  'Escapes/Defense': 'escapes-defense',
  Submissions: 'submissions',
  Conditioning: 'conditioning',
  Mindset: 'mindset',
};

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        cell += '"';
        i += 1;
      } else if (ch === '"') quoted = false;
      else cell += ch;
      continue;
    }
    if (ch === '"') quoted = true;
    else if (ch === ',') {
      row.push(cell);
      cell = '';
    } else if (ch === '\n') {
      row.push(cell.replace(/\r$/, ''));
      rows.push(row);
      row = [];
      cell = '';
    } else cell += ch;
  }
  if (cell || row.length) {
    row.push(cell.replace(/\r$/, ''));
    rows.push(row);
  }
  return rows.filter((r) => r.some((c) => c.trim()));
}

const raw = readFileSync('docs/glossary/BJJ_glossary_D8_only.csv', 'utf8').replace(/^\uFEFF/, '');
const [header, ...body] = parseCsv(raw);
const col = (name) => {
  const index = header.indexOf(name);
  if (index < 0) throw new Error(`Missing column ${name}`);
  return index;
};
const terms = body.map((cells) => {
  const face = FACE_IDS[cells[col('d8_face')].trim()];
  if (!face) throw new Error(`Row ${cells[0]} has no D8 face: ${cells[col('d8_face')]}`);
  return {
    term: cells[col('term')].trim(),
    aliases: cells[col('aliases')]
      .split(/[;|]/)
      .map((alias) => alias.trim())
      .filter(Boolean),
    definition: cells[col('short_definition')].trim(),
    faceId: face,
    subFactor: cells[col('sub_factor')].trim(),
  };
});

const out = `/**
 * GENERATED by scripts/build-glossary.mjs from docs/glossary/BJJ_glossary_D8_only.csv.
 * Do not edit by hand. Edit the CSV and rerun the script.
 * The core D8 glossary: ${terms.length} terms, every one on a D8 face.
 */
import type { IndexFaceId } from './indexCards.ts';

export type GlossaryRow = {
  term: string;
  aliases: readonly string[];
  definition: string;
  faceId: IndexFaceId;
  subFactor: string;
};

export const GLOSSARY_ROWS: readonly GlossaryRow[] = ${JSON.stringify(terms, null, 2)};
`;
writeFileSync('src/lib/glossaryData.ts', out);
console.log(`Wrote ${terms.length} glossary terms.`);
